#!/usr/bin/env python3
"""Regenerate docs/platform-tour.md from a running platform cluster.

Runs the discovery commands of the tour against the cluster, replaces every address that is
not a private address of the cluster (10.0.0.0/8) with an address of the documentation ranges
(RFC 5737), consistently, and replaces the names given with --replace. Run it after each test
cycle, read the diff, commit.

    tests/tour/capture.py --kubeconfig platform.kubeconfig [--replace real=example ...] \
        [--kubectl kubectl] [--clusterctl clusterctl] > docs/platform-tour.md
"""

import argparse
import ipaddress
import re
import subprocess

DOC_RANGES = [ipaddress.ip_network(n) for n in ("192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24")]

STEPS = [
    ("Where am I, who am I", "The kubeconfig points at the API floating IP on the administration network; "
     "its user is the cluster administrator created by kubeadm.",
     [["kubectl", "cluster-info"], ["kubectl", "version"], ["kubectl", "auth", "whoami"]]),
    ("How the cluster is built", "Cluster API objects live in the cluster itself after `clusterctl move`: "
     "one Machine per server, created from the ClusterClass.",
     [["clusterctl", "describe", "cluster", "platform", "-n", "platform"],
      ["kubectl", "-n", "platform", "get", "clusterclass,cluster,kubeadmcontrolplane,machinedeployment"],
      ["kubectl", "-n", "platform", "get", "machines,openstackmachines"]]),
    ("Nodes", "Three control-plane nodes and two workers, all on the cluster network; the cloud "
     "controller manager sets their addresses and provider IDs.",
     [["kubectl", "get", "nodes", "-o", "wide"]]),
    ("What runs", "System components in kube-system, Cluster API and its providers, then the add-ons "
     "installed by CAAPH.",
     [["kubectl", "get", "namespaces"], ["kubectl", "get", "deploy,daemonset", "-A"],
      ["kubectl", "-n", "platform", "get", "helmchartproxies,helmreleaseproxies"]]),
    ("How it is exposed", "Each `LoadBalancer` Service is an Octavia load balancer created by the cloud "
     "controller manager; its floating IP, on the plane it is published on, is created by the stack "
     "and requested by the Service.",
     [["kubectl", "get", "svc", "-A", "--field-selector", "spec.type=LoadBalancer"],
      ["kubectl", "get", "gatewayclass,gateway,httproute", "-A"]]),
    ("Storage", "Cinder CSI provides the default storage class.", [["kubectl", "get", "storageclass"]]),
    ("Resource usage", "metrics-server feeds `kubectl top`.", [["kubectl", "top", "nodes"]]),
]


class Sanitizer:
    def __init__(self, replacements):
        self.map = {}
        self.next = [0] * len(DOC_RANGES)
        self.replacements = replacements

    def _address(self, match):
        text = match.group(0)
        try:
            ip = ipaddress.ip_address(text)
        except ValueError:
            return text
        if ip in ipaddress.ip_network("10.0.0.0/8") or ip.is_loopback or ip.is_unspecified:
            return text
        if text not in self.map:
            i = len(self.map) % len(DOC_RANGES)
            self.next[i] += 1
            self.map[text] = str(DOC_RANGES[i].network_address + self.next[i])
        return self.map[text]

    def __call__(self, text):
        for real, example in self.replacements:
            text = text.replace(real, example)
        text = re.sub(r"X509SHA256=[0-9a-f]+", "X509SHA256=...", text)
        return re.sub(r"\b\d{1,3}(?:\.\d{1,3}){3}\b", self._address, text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kubeconfig", required=True)
    ap.add_argument("--kubectl", default="kubectl")
    ap.add_argument("--clusterctl", default="clusterctl")
    ap.add_argument("--replace", action="append", default=[], help="real=example, applied before addresses")
    args = ap.parse_args()
    clean = Sanitizer([tuple(r.split("=", 1)) for r in args.replace])
    tools = {"kubectl": args.kubectl, "clusterctl": args.clusterctl}

    print("# Platform tour\n")
    print("A guided discovery of the `platform` cluster, with the outputs of a test deployment. "
          "Addresses outside the cluster network are replaced with documentation addresses; the "
          "outputs are regenerated by [`tests/tour/capture.py`](../tests/tour/capture.py) after each "
          "test cycle.\n")
    print("Access: the kubeconfig of the cluster (`/opt/platform/<cluster>.kubeconfig` on the bootstrap "
          "instance), from an administration source admitted on the API.\n")
    for title, text, commands in STEPS:
        print(f"## {title}\n\n{text}\n")
        for cmd in commands:
            run = [tools[cmd[0]]] + cmd[1:] + ["--kubeconfig", args.kubeconfig]
            r = subprocess.run(run, capture_output=True, text=True, timeout=120)
            out = (r.stdout + r.stderr).rstrip()
            print("```console\n$ " + " ".join(cmd) + "\n" + clean(out) + "\n```\n")


if __name__ == "__main__":
    main()
